export function getSeedQuestions(): SeedQuestion[] {
  const originals = Object.entries(bank).flatMap(([category, entries]) => {
    const notes = answerNotes[category];
    if (
      !notes ||
      notes.length !== entries.length ||
      notes.some((note) => note.length < 40)
    ) {
      throw new Error(
        `${category}: each question needs a substantive answer note`,
      );
    }
    return entries
      .map(([subcategory, difficulty, question, answer], index) => {
        const context = answerContext[category]?.[subcategory];
        if (!context)
          throw new Error(`Missing answer context: ${category}/${subcategory}`);
        return {
          category,
          subcategory,
          difficulty,
          question,
          answer: `${expandedAnswers[question] ?? `### 核心结论\n\n${answer}`}\n\n### 原理与实现\n\n${context}\n\n### 场景与边界\n\n${notes[index]}\n\n### 岗位场景中的验证\n\n${roleApplications[category]}`,
          tags: [category, subcategory],
        };
      })
      .filter((row) => !retiredOriginalQuestions.has(row.question));
  });
  return [
    ...originals,
    ...expandTopics([
      ...agentTopics,
      ...llmTopics.filter((topic) => !retiredLlmTopics.has(topic.subcategory)),
      ...ragTopics,
      ...appTopics,
      ...foundationTopics,
      ...appliedTopics,
    ]),
  ];
}
